//! Small, purpose-built BBCode reader for Godot's native symbol docs.
//!
//! Godot returns documentation as BBCode (`[method print]`, `[member Node.name]`,
//! `[code]...[/code]`, `[url=...]...[/url]`). The editor only needs text and
//! clickable references, so this parser deliberately ignores layout-only tags
//! and keeps the useful spans.

/// A clickable target in a documentation span.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum DocLink {
    Native { class: String, symbol: String },
    Url(String),
}

/// Visual style of a documentation span.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DocStyle {
    Normal,
    Bold,
    Italic,
    Code,
    Link,
    /// Section / declaration heading generated by the docs view.
    Heading,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DocSpan {
    pub text: String,
    pub style: DocStyle,
    pub link: Option<DocLink>,
}

impl DocSpan {
    fn new(text: String, style: DocStyle, link: Option<DocLink>) -> Self {
        Self { text, style, link }
    }
}

/// Parses Godot BBCode, resolving bare member references against `class`.
pub fn parse(input: &str, class: &str) -> Vec<DocSpan> {
    let mut out = Vec::new();
    let mut text = String::new();
    let mut bold = 0u32;
    let mut italic = 0u32;
    let mut code = 0u32;
    let mut i = 0usize;
    while i < input.len() {
        if input.as_bytes()[i] == b'[' {
            if let Some(close_rel) = input[i..].find(']') {
                let close = i + close_rel;
                let tag = &input[i + 1..close];
                flush(&mut out, &mut text, bold, italic, code, None);
                i = close + 1;

                // [url=...]...[/url]
                if let Some(url) = tag.strip_prefix("url=") {
                    let end_tag = "[/url]";
                    if let Some(end_rel) = input[i..].find(end_tag) {
                        let body = input[i..i + end_rel].to_string();
                        let target = url.trim().to_string();
                        push(&mut out, body, DocStyle::Link, Some(DocLink::Url(target)));
                        i += end_rel + end_tag.len();
                    }
                    continue;
                }
                if tag == "url" {
                    let end_tag = "[/url]";
                    if let Some(end_rel) = input[i..].find(end_tag) {
                        let body = input[i..i + end_rel].to_string();
                        let target = body.trim().to_string();
                        push(&mut out, body, DocStyle::Link, Some(DocLink::Url(target)));
                        i += end_rel + end_tag.len();
                    }
                    continue;
                }

                match tag {
                    "b" => bold = bold.saturating_add(1),
                    "/b" => bold = bold.saturating_sub(1),
                    "i" => italic = italic.saturating_add(1),
                    "/i" => italic = italic.saturating_sub(1),
                    "code" | "codeblock" | "gdscript" | "csharp" | "code skip-lint" => {
                        code = code.saturating_add(1);
                    }
                    "/code" | "/codeblock" | "/gdscript" | "/csharp" => {
                        code = code.saturating_sub(1);
                    }
                    "codeblocks" | "/codeblocks" | "center" | "/center" | "u" | "/u" => {}
                    "br" => push(&mut out, "\n".into(), DocStyle::Normal, None),
                    _ => {
                        if let Some((kind, value)) = tag.split_once(' ') {
                            let value = value.trim();
                            match kind {
                                "method" | "member" | "constant" | "signal" | "constructor"
                                | "operator" => {
                                    let (target_class, target_symbol) = reference(value, class);
                                    push(
                                        &mut out,
                                        value.to_string(),
                                        DocStyle::Link,
                                        Some(DocLink::Native {
                                            class: target_class,
                                            symbol: target_symbol,
                                        }),
                                    );
                                    continue;
                                }
                                "param" => {
                                    push(&mut out, value.to_string(), DocStyle::Code, None);
                                    continue;
                                }
                                _ => {}
                            }
                        }
                        // A bare class reference such as [Node].
                        let looks_like_class = tag
                            .chars()
                            .next()
                            .is_some_and(|ch| ch.is_alphabetic() || ch == '_' || ch == '@');
                        if !tag.is_empty()
                            && looks_like_class
                            && !tag.starts_with('/')
                            && !tag.contains('=')
                            && !tag.contains(' ')
                        {
                            push(
                                &mut out,
                                tag.to_string(),
                                DocStyle::Link,
                                Some(DocLink::Native {
                                    class: tag.to_string(),
                                    symbol: tag.to_string(),
                                }),
                            );
                        } else if !tag.starts_with('/') && !tag.contains('=') {
                            // Not a known tag or class link: keep the literal
                            // brackets instead of silently dropping code text.
                            text.push('[');
                            text.push_str(tag);
                            text.push(']');
                        }
                    }
                }
                continue;
            }
        }
        let ch = input[i..].chars().next().unwrap_or(' ');
        text.push(ch);
        i += ch.len_utf8();
    }
    flush(&mut out, &mut text, bold, italic, code, None);
    out
}

fn reference(value: &str, default_class: &str) -> (String, String) {
    match value.split_once('.') {
        Some((class, symbol)) => (class.to_string(), symbol.to_string()),
        None => (default_class.to_string(), value.to_string()),
    }
}

fn push(out: &mut Vec<DocSpan>, text: String, style: DocStyle, link: Option<DocLink>) {
    if !text.is_empty() {
        out.push(DocSpan::new(text, style, link));
    }
}

fn flush(
    out: &mut Vec<DocSpan>,
    text: &mut String,
    bold: u32,
    italic: u32,
    code: u32,
    link: Option<DocLink>,
) {
    if text.is_empty() {
        return;
    }
    let style = if code > 0 {
        DocStyle::Code
    } else if link.is_some() {
        DocStyle::Link
    } else if bold > 0 {
        DocStyle::Bold
    } else if italic > 0 {
        DocStyle::Italic
    } else {
        DocStyle::Normal
    };
    out.push(DocSpan::new(std::mem::take(text), style, link));
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_godot_references_and_code() {
        let spans = parse(
            "Use [method print] or [member Node.name]. See [Node] and [code]x = 1[/code].",
            "Node",
        );
        assert!(spans.iter().any(|span| {
            span.text == "print"
                && span.style == DocStyle::Link
                && span.link
                    == Some(DocLink::Native {
                        class: "Node".into(),
                        symbol: "print".into(),
                    })
        }));
        assert!(spans.iter().any(|span| {
            span.text == "Node.name"
                && span.link
                    == Some(DocLink::Native {
                        class: "Node".into(),
                        symbol: "name".into(),
                    })
        }));
        assert!(spans.iter().any(|span| {
            span.text == "Node"
                && span.link
                    == Some(DocLink::Native {
                        class: "Node".into(),
                        symbol: "Node".into(),
                    })
        }));
        assert!(spans
            .iter()
            .any(|span| span.text == "x = 1" && span.style == DocStyle::Code));
        let wrapped = parse("[codeblocks][code]x[/code][/codeblocks]", "Node");
        assert!(wrapped
            .iter()
            .any(|span| span.text == "x" && span.style == DocStyle::Code));
        assert!(!wrapped.iter().any(|span| span.text == "codeblocks"));
    }

    #[test]
    fn parses_urls_and_escaped_brackets() {
        let spans = parse("Use [url=https://godotengine.org]Godot[/url] now.", "Node");
        assert!(spans.iter().any(|span| {
            span.text == "Godot"
                && span.link == Some(DocLink::Url("https://godotengine.org".into()))
        }));
        let spans = parse("array[0]", "Node");
        assert_eq!(
            spans
                .iter()
                .map(|span| span.text.as_str())
                .collect::<String>(),
            "array[0]"
        );
    }
}
